using System.Collections.Generic;
using System.Linq;
using UnityEditor;
using UnityEngine;
using UnityEngine.Rendering;

/// <summary>
/// Cuts the map's whole-map meshes (the street surfaces and paint, the lot tints, the streams, the plinths, the long
/// landmark blocks) into square tiles, one child object per tile with its own collider. A mesh is culled as a whole, so
/// a road net 800 m across was drawn in full whenever any metre of it was in view: about 300k triangles from the boat's
/// start, most of them far behind the fog. Tiled, only the tiles in view are drawn. The picture is the same; nothing moves.
/// Run by <see cref="MapFinisher"/> after the map is sorted and before the NavMesh is baked.
/// </summary>
public static class MeshTiler
{
    /// <summary>Tile size in world metres, the same as the ground's chunks.</summary>
    public const float TileSize = 64f;
    /// <summary>A mesh is tiled when it is wider than this (world metres) in x or z...</summary>
    public const float MinSpan = 96f;
    /// <summary>...and has at least this many triangles (a few big quads gain nothing from it).</summary>
    public const int MinTriangles = 1000;
    public const string BundleName = "Tiled_Meshes.asset";

    // Groups left alone: the rows have their own LOD cull, foliage and props are small objects already, and each compound
    // wall stays one drawn and solid piece (tests and the gates find a wall by its own renderer).
    static readonly string[] Skip = { MapGroups.Residential, MapGroups.CompoundWalls, FoliageBuilder.GroupName, PropBuilder.GroupName };

    // Only plain drawn parts are tiled; anything with a behaviour of its own on it is kept whole.
    static readonly System.Type[] Plain = { typeof(Transform), typeof(MeshFilter), typeof(MeshRenderer), typeof(MeshCollider) };

    /// <summary>Tiles every big plain mesh under the map's root. Returns a line for the build report.</summary>
    public static string Tile(Transform root, string generatedFolder)
    {
        string path = generatedFolder + "/" + BundleName;
        var bundle = AssetDatabase.LoadAssetAtPath<MockMeshBundle>(path);
        if (bundle == null)
        {
            bundle = ScriptableObject.CreateInstance<MockMeshBundle>();
            bundle.note = "Generated by MeshTiler (Bayanihan > Build Mabuhay Gameplay Scene): the whole-map meshes cut into " +
                          TileSize + " m tiles so only what is in view is drawn. Rebuilt each time.";
            AssetDatabase.CreateAsset(bundle, path);
        }
        foreach (var o in AssetDatabase.LoadAllAssetRepresentationsAtPath(path)) Object.DestroyImmediate(o, true);

        var skip = Skip.Select(root.Find).Where(t => t != null).ToList();
        int meshes = 0, tiles = 0;
        foreach (var filter in root.GetComponentsInChildren<MeshFilter>(true).ToList())
        {
            var go = filter.gameObject;
            var mesh = filter.sharedMesh;
            var renderer = go.GetComponent<MeshRenderer>();
            if (mesh == null || renderer == null || go.transform.childCount > 0) continue;
            if (skip.Any(s => go.transform.IsChildOf(s)) || go.GetComponentInParent<LODGroup>() != null) continue;
            if (go.GetComponents<Component>().Any(c => !Plain.Contains(c.GetType()))) continue;
            var span = renderer.bounds.size;
            if (Mathf.Max(span.x, span.z) < MinSpan || TriangleCount(mesh) < MinTriangles) continue;

            int made = Split(go, mesh, renderer, bundle);
            if (made > 1) { meshes++; tiles += made; }
        }
        EditorUtility.SetDirty(bundle);
        return "Tiled: " + meshes + " whole-map meshes cut into " + tiles + " tiles of " + TileSize + " m.";
    }

    static long TriangleCount(Mesh m)
    {
        long t = 0;
        for (int s = 0; s < m.subMeshCount; s++) t += m.GetIndexCount(s) / 3;
        return t;
    }

    /// <summary>
    /// Cuts one mesh by the tile each triangle's middle falls in (world x, z). The tiles are children named like the
    /// original, at its own place, so they keep its local space and its name (tests and tools look for "road_...").
    /// Returns the number of tiles; 1 means it fitted in one and was left as it was.
    /// </summary>
    static int Split(GameObject go, Mesh mesh, MeshRenderer renderer, MockMeshBundle bundle)
    {
        var toWorld = go.transform.localToWorldMatrix;
        var verts = mesh.vertices;
        var normals = mesh.normals;
        var tangents = mesh.tangents;
        var uv = mesh.uv;
        var uv2 = mesh.uv2;
        var colors = mesh.colors;

        // tile -> per submesh, the triangles' old indices
        var byTile = new Dictionary<Vector2Int, List<int>[]>();
        for (int s = 0; s < mesh.subMeshCount; s++)
        {
            if (mesh.GetTopology(s) != MeshTopology.Triangles) return 1;
            var tris = mesh.GetTriangles(s);
            for (int i = 0; i < tris.Length; i += 3)
            {
                var mid = toWorld.MultiplyPoint3x4((verts[tris[i]] + verts[tris[i + 1]] + verts[tris[i + 2]]) / 3f);
                var key = new Vector2Int(Mathf.FloorToInt(mid.x / TileSize), Mathf.FloorToInt(mid.z / TileSize));
                if (!byTile.TryGetValue(key, out var lists))
                {
                    byTile[key] = lists = new List<int>[mesh.subMeshCount];
                    for (int k = 0; k < lists.Length; k++) lists[k] = new List<int>();
                }
                lists[s].Add(tris[i]); lists[s].Add(tris[i + 1]); lists[s].Add(tris[i + 2]);
            }
        }
        if (byTile.Count <= 1) return 1;

        var collider = go.GetComponent<MeshCollider>();
        var flags = GameObjectUtility.GetStaticEditorFlags(go);
        foreach (var kv in byTile.OrderBy(k => k.Key.x).ThenBy(k => k.Key.y))
        {
            var remap = new Dictionary<int, int>();
            var order = new List<int>();
            int Map(int old)
            {
                if (!remap.TryGetValue(old, out int n)) { n = order.Count; remap[old] = n; order.Add(old); }
                return n;
            }
            var subs = kv.Value.Select(list => list.Select(Map).ToArray()).ToArray();

            var piece = new Mesh { name = mesh.name + " " + kv.Key.x + "," + kv.Key.y };
            if (order.Count > 65535) piece.indexFormat = IndexFormat.UInt32;
            piece.vertices = order.Select(i => verts[i]).ToArray();
            if (normals.Length == verts.Length) piece.normals = order.Select(i => normals[i]).ToArray();
            if (tangents.Length == verts.Length) piece.tangents = order.Select(i => tangents[i]).ToArray();
            if (uv.Length == verts.Length) piece.uv = order.Select(i => uv[i]).ToArray();
            if (uv2.Length == verts.Length) piece.uv2 = order.Select(i => uv2[i]).ToArray();
            if (colors.Length == verts.Length) piece.colors = order.Select(i => colors[i]).ToArray();
            piece.subMeshCount = subs.Length;
            for (int s = 0; s < subs.Length; s++) piece.SetTriangles(subs[s], s, false);
            piece.RecalculateBounds();
            AssetDatabase.AddObjectToAsset(piece, bundle);

            var tile = new GameObject(go.name);
            tile.layer = go.layer;
            tile.tag = go.tag;
            tile.transform.SetParent(go.transform, false);
            tile.AddComponent<MeshFilter>().sharedMesh = piece;
            var r = tile.AddComponent<MeshRenderer>();
            r.sharedMaterials = renderer.sharedMaterials;
            r.shadowCastingMode = renderer.shadowCastingMode;
            r.receiveShadows = renderer.receiveShadows;
            r.lightProbeUsage = renderer.lightProbeUsage;
            r.reflectionProbeUsage = renderer.reflectionProbeUsage;
            r.renderingLayerMask = renderer.renderingLayerMask;
            r.enabled = renderer.enabled;
            if (collider != null)
            {
                var c = tile.AddComponent<MeshCollider>();
                c.sharedMesh = piece;
                c.sharedMaterial = collider.sharedMaterial;
                c.convex = collider.convex;
                c.isTrigger = collider.isTrigger;
                c.enabled = collider.enabled;
            }
            GameObjectUtility.SetStaticEditorFlags(tile, flags);
        }

        if (collider != null) Object.DestroyImmediate(collider);
        Object.DestroyImmediate(renderer);
        Object.DestroyImmediate(go.GetComponent<MeshFilter>());
        return byTile.Count;
    }
}
